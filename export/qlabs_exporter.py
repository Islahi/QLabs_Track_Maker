def _asg_rotated_square(
    qlabs,
    obj,
    center_point,
    side,
    angle_deg,
    depth,
    color,
    face_z=2.45,
    front=0.055,
):
    angle = math.radians(angle_deg)
    half = side / 2.0
    dx = math.cos(angle) * half
    dz = math.sin(angle) * half
    p1 = (center_point[0] - dx, center_point[1] - dz)
    p2 = (center_point[0] + dx, center_point[1] + dz)
    return _asg_spawn_shape_world(
        qlabs,
        obj,
        _asg_world(obj, center_point[0], face_z + center_point[1], front),
        _asg_segment_rotation(obj, p1, p2),
        [side, depth, side],
        QLabsBasicShape.SHAPE_CUBE,
        color,
        roughness=0.14,
        collisions=False,
    )


