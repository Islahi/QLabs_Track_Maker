def _asg_tangent(obj):
    yaw = _asg_yaw(obj)
    return [math.cos(yaw), math.sin(yaw), 0.0]


def _asg_left_axis(obj):
    yaw = _asg_yaw(obj)
    return [math.sin(yaw), -math.cos(yaw), 0.0]


def _asg_world(obj, lateral=0.0, z=0.0, front=0.0):
    """Map sign-local coordinates to world coordinates.

    lateral: +left on the sign face
    z:       height above the item's base
    front:   +toward the approaching driver / visible sign face (-tangent)
    """
    base = _asg_base(obj)
    scale = _asg_scale(obj)
    t = _asg_tangent(obj)
    n = _asg_left_axis(obj)
    return [
        base[0] + n[0] * lateral * scale - t[0] * front * scale,
        base[1] + n[1] * lateral * scale - t[1] * front * scale,
        base[2] + z * scale,
    ]


def _asg_spawn_shape_world(
    qlabs,
    obj,
    location,
    rotation,
    dimensions,
    configuration,
    color,
    roughness=0.25,
    collisions=False,
):
    actor = QLabsBasicShape(qlabs)
    scale = _asg_scale(obj)
    actor.spawn(
        location=[float(v) for v in location],
        rotation=[float(v) for v in rotation],
        scale=[max(0.001, float(v) * scale) for v in dimensions],
        configuration=configuration,
        waitForConfirmation=True,
    )
    actor.set_material_properties(
        color=list(color),
        roughness=float(roughness),
        metallic=False,
        waitForConfirmation=True,
    )
    actor.set_enable_dynamics(False, waitForConfirmation=True)
    actor.set_enable_collisions(bool(collisions), waitForConfirmation=True)
    return actor


