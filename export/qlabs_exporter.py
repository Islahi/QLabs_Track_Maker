def _asg_cross(a, b):
    return [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ]


def _asg_matrix_to_euler_zyx(matrix):
    r00, r01, r02 = matrix[0]
    r10, r11, r12 = matrix[1]
    r20, r21, r22 = matrix[2]
    if abs(r20) < 1.0 - 1e-8:
        pitch = -math.asin(r20)
        roll = math.atan2(r21, r22)
        yaw = math.atan2(r10, r00)
    else:
        pitch = -math.copysign(math.pi / 2.0, r20)
        roll = 0.0
        yaw = math.atan2(-r01, r11)
    return [roll, pitch, yaw]


def _asg_segment_rotation(obj, p1, p2, coord_scale=1.0):
    du = (float(p2[0]) - float(p1[0])) * coord_scale
    dv = (float(p2[1]) - float(p1[1])) * coord_scale
    length = math.hypot(du, dv)
    if length <= 1e-9:
        return None
    n = _asg_left_axis(obj)
    t = _asg_tangent(obj)
    face_normal = [-t[0], -t[1], 0.0]
    x_axis = [n[0] * du / length, n[1] * du / length, dv / length]
    y_axis = face_normal
    z_axis = _asg_cross(x_axis, y_axis)
    return _asg_matrix_to_euler_zyx([
        [x_axis[0], y_axis[0], z_axis[0]],
        [x_axis[1], y_axis[1], z_axis[1]],
        [x_axis[2], y_axis[2], z_axis[2]],
    ])


def _asg_spawn_segment(
    qlabs,
    obj,
    p1,
    p2,
    width,
    depth,
    color,
    face_z=2.45,
    front=0.055,
    coord_scale=1.0,
    overlap=1.08,
    roughness=0.12,
):
    du = (float(p2[0]) - float(p1[0])) * coord_scale
    dv = (float(p2[1]) - float(p1[1])) * coord_scale
    length = math.hypot(du, dv)
    if length <= 1e-9:
        return None
    midpoint = (
        (float(p1[0]) + float(p2[0])) / 2.0 * coord_scale,
        (float(p1[1]) + float(p2[1])) / 2.0 * coord_scale,
    )
    location = _asg_world(obj, midpoint[0], face_z + midpoint[1], front)
    return _asg_spawn_shape_world(
        qlabs,
        obj,
        location,
        _asg_segment_rotation(obj, p1, p2, coord_scale=coord_scale),
        [length * overlap, depth, width],
        QLabsBasicShape.SHAPE_CUBE,
        color,
        roughness=roughness,
        collisions=False,
    )


def _asg_polyline(
    qlabs,
    obj,
    points,
    width,
    depth,
    color,
    face_z=2.45,
    front=0.055,
    coord_scale=1.0,
    subdivisions=1,
    overlap=1.08,
):
    if len(points) < 2:
        return
    for index in range(len(points) - 1):
        p1 = points[index]
        p2 = points[index + 1]
        steps = max(1, int(subdivisions))
        previous = p1
        for step in range(1, steps + 1):
            f = step / steps
            current = (
                p1[0] + (p2[0] - p1[0]) * f,
                p1[1] + (p2[1] - p1[1]) * f,
            )
            _asg_spawn_segment(
                qlabs, obj, previous, current, width, depth, color,
                face_z=face_z, front=front, coord_scale=coord_scale,
                overlap=overlap,
            )
            previous = current


def _asg_arc_points(cx, cz, radius, start_deg, end_deg, segments):
    points = []
    for index in range(segments + 1):
        f = index / segments
        angle = math.radians(start_deg + (end_deg - start_deg) * f)
        points.append((cx + radius * math.cos(angle), cz + radius * math.sin(angle)))
    return points


def _asg_filled_triangle(
    qlabs,
    obj,
    tip,
    back_a,
    back_b,
    width,
    depth,
    color,
    face_z=2.45,
    front=0.055,
    coord_scale=1.0,
    layers=14,
):
    layers = max(2, int(layers))
    for index in range(layers):
        f = (index + 0.5) / layers
        a = (
            back_a[0] + (tip[0] - back_a[0]) * f,
            back_a[1] + (tip[1] - back_a[1]) * f,
        )
        b = (
            back_b[0] + (tip[0] - back_b[0]) * f,
            back_b[1] + (tip[1] - back_b[1]) * f,
        )
        _asg_spawn_segment(
            qlabs, obj, a, b, width * 1.05, depth, color,
            face_z=face_z, front=front, coord_scale=coord_scale,
            overlap=1.08,
        )


