def _compact_generated_source(
    source: str, track_data: dict, workspace_label: str
) -> str:
    """Keep only runtime code required by the objects in this exported map."""
    features = _export_features(track_data)
    module = ast.parse(source)
    module = _FeatureSpecializer(features).visit(module)
    ast.fix_missing_locations(module)
    module = _prune_module(module)

    body = ast.unparse(module).rstrip() + "\n"
    summary = _feature_summary(features)
    feature_text = ", ".join(summary) if summary else "no map objects"

    header = (
        "# Generated by QLabs Track Editor\n"
        "# Compact feature-aware export: only code required by this map is included.\n"
        f"# Workspace: {workspace_label}\n"
        f"# Included: {feature_text}\n\n"
    )
    return header + body
