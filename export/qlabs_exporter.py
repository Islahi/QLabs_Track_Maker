def _asg_spawn_right_or_left(qlabs, obj):
    white = [0.98, 0.98, 0.98]
    blue = [0.09, 0.31, 0.67]
    _asg_pole(qlabs, obj, 2.30, 0.08, 0.10)
    _asg_spawn_disc(qlabs, obj, 1.22, white, z=2.45, depth=0.08)
    _asg_spawn_disc(qlabs, obj, 1.14, blue, z=2.45, front=0.008, depth=0.0704)
    cs = 0.92
    width = 0.060 * cs

    def aligned(start, shaft_end, head_length=0.20, head_half_width=0.15):
        dx = shaft_end[0] - start[0]
        dz = shaft_end[1] - start[1]
        length = math.hypot(dx, dz)
        ux, uz = dx / length, dz / length
        tip = (shaft_end[0] + ux * head_length, shaft_end[1] + uz * head_length)
        px, pz = -uz, ux
        a = (shaft_end[0] + px * head_half_width, shaft_end[1] + pz * head_half_width)
        b = (shaft_end[0] - px * head_half_width, shaft_end[1] - pz * head_half_width)
        return tip, a, b

    for start, end in [((-0.06, 0.24), (-0.25, 0.05)), ((0.06, 0.24), (0.25, 0.05))]:
        tip, a, b = aligned(start, end)
        _asg_polyline(
            qlabs, obj, [start, end], width, 0.025, white,
            front=0.060, coord_scale=cs, subdivisions=8,
        )
        _asg_arrow_head(
            qlabs, obj, tip, a, b, width, 0.025, white,
            front=0.060, coord_scale=cs, layers=16,
        )


