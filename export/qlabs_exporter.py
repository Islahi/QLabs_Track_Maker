def _asg_warning_triangle(
    qlabs,
    obj,
    half_width=0.62,
    bottom_z=-0.52,
    top_z=0.58,
    rows=42,
    border_width=0.095,
    face_z=2.45,
    front=0.055,
):
    white = [0.98, 0.98, 0.98]
    red = [0.92, 0.06, 0.06]
    total_height = top_z - bottom_z
    row_height = total_height / rows * 1.18
    for index in range(rows):
        f = (index + 0.5) / rows
        z = bottom_z + total_height * f
        hw = half_width * (1.0 - f)
        _asg_spawn_segment(
            qlabs, obj, (-hw, z), (hw, z), row_height, 0.035, white,
            face_z=face_z, front=front, overlap=1.04,
        )
    apex = (0.0, top_z)
    left = (-half_width, bottom_z)
    right = (half_width, bottom_z)
    for p1, p2 in ((left, apex), (apex, right), (right, left)):
        _asg_spawn_segment(
            qlabs, obj, p1, p2, border_width, 0.033, red,
            face_z=face_z, front=front + 0.012, overlap=1.02,
        )


