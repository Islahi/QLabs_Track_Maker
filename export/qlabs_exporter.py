def _asg_spawn_speed_limit(qlabs, obj, speed_kmh):
    red = [0.85, 0.03, 0.03]
    white = [0.96, 0.96, 0.96]
    black = [0.02, 0.02, 0.02]
    # Known-good dimensions from the orientation validation file.
    _asg_spawn_cube(
        qlabs, obj, 0.0, 1.50, 0.0, [0.16, 0.16, 3.0], [0.45, 0.45, 0.45],
        rotation=[0.0, 0.0, 0.0], roughness=0.8, collisions=True,
    )
    _asg_spawn_disc(qlabs, obj, 2.20, red, z=3.0, front=0.0, depth=0.12)
    _asg_spawn_disc(qlabs, obj, 2.20 * 0.78, white, z=3.0, front=0.07, depth=0.066)

    segments = {
        "0": {"a", "b", "c", "d", "e", "f"},
        "1": {"b", "c"},
        "2": {"a", "b", "g", "e", "d"},
        "3": {"a", "b", "c", "d", "g"},
        "4": {"f", "g", "b", "c"},
        "5": {"a", "f", "g", "c", "d"},
        "6": {"a", "f", "g", "e", "c", "d"},
        "7": {"a", "b", "c"},
        "8": {"a", "b", "c", "d", "e", "f", "g"},
        "9": {"a", "b", "c", "d", "f", "g"},
    }
    number = str(int(speed_kmh))
    digit_width = 0.42
    digit_height = 0.88
    digit_gap = 0.14
    thickness = 0.095
    depth = 0.055
    total_width = len(number) * digit_width + (len(number) - 1) * digit_gap
    first = -total_width / 2.0 + digit_width / 2.0
    horizontal_length = digit_width * 0.82
    vertical_length = digit_height * 0.38
    defs = {
        "a": (0.0, +digit_height / 2.0, horizontal_length, thickness),
        "g": (0.0, 0.0, horizontal_length, thickness),
        "d": (0.0, -digit_height / 2.0, horizontal_length, thickness),
        "f": (-digit_width / 2.0, +digit_height / 4.0, thickness, vertical_length),
        "b": (+digit_width / 2.0, +digit_height / 4.0, thickness, vertical_length),
        "e": (-digit_width / 2.0, -digit_height / 4.0, thickness, vertical_length),
        "c": (+digit_width / 2.0, -digit_height / 4.0, thickness, vertical_length),
    }
    yaw = _asg_yaw(obj)
    for digit_index, digit in enumerate(number):
        center = first + digit_index * (digit_width + digit_gap)
        for name in segments.get(digit, set()):
            dx, dz, sx, sz = defs[name]
            location = _asg_world(obj, center + dx, 3.0 + dz, 0.13)
            _asg_spawn_shape_world(
                qlabs, obj, location, [0.0, 0.0, yaw + math.pi / 2.0],
                [sx, depth, sz], QLabsBasicShape.SHAPE_CUBE, black,
                roughness=0.8, collisions=False,
            )


def _spawn_approved_catalog_sign(qlabs, obj, sign_type):
    if sign_type == "front_or_right":
        return _asg_spawn_front_or_side(qlabs, obj, left=False)
    if sign_type == "front_or_left":
        return _asg_spawn_front_or_side(qlabs, obj, left=True)
    if sign_type == "right_turn":
        return _asg_spawn_turn_warning(qlabs, obj, left=False)
    if sign_type == "left_turn":
        return _asg_spawn_turn_warning(qlabs, obj, left=True)
    if sign_type == "u_turn":
        return _asg_spawn_u_turn(qlabs, obj, prohibited=False)
    if sign_type == "no_u_turn":
        return _asg_spawn_u_turn(qlabs, obj, prohibited=True)
    if sign_type == "parking":
        return _asg_spawn_parking(qlabs, obj)
    if sign_type == "no_parking":
        return _asg_spawn_no_parking(qlabs, obj)
    if sign_type == "no_overtaking":
        return _asg_spawn_no_overtaking(qlabs, obj)
