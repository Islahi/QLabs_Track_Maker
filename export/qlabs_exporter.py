def spawn_catalog_traffic_sign(qlabs, obj):
    """Spawn one Plane-validated custom traffic sign.

    Stop, Yield, and Roundabout are native QLabs actor types and are exported
    through their dedicated editor objects, not through this custom catalog.
    Unsupported legacy catalog keys are skipped instead of generating the old
    approximate fallback geometry.
    """
    sign_type = str(obj.get("sign_type", "front_or_right"))

    if sign_type not in APPROVED_CUSTOM_SIGN_TYPES:
        print(
            "Skipping unsupported legacy custom traffic sign: "
            + sign_type
        )
        return None

    return _spawn_approved_catalog_sign(qlabs, obj, sign_type)


