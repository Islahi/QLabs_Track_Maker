def _export_features(track_data: dict) -> dict:
    objects = list(track_data.get("objects", []) or [])
    object_types = {str(obj.get("type", "")) for obj in objects}

    movement_types = {
        str(obj.get("type", ""))
        for obj in objects
        if str(obj.get("type", "")) in _MOVABLE_ACTOR_TYPES
        and bool(obj.get("move_on_activation", False))
        and (
            bool(obj.get("path_points"))
            or abs(
                float(obj.get("destination_x_m", obj.get("x", 0.0)))
                - float(obj.get("x", 0.0))
            )
            > 1e-9
            or abs(
                float(obj.get("destination_y_m", obj.get("y", 0.0)))
                - float(obj.get("y", 0.0))
            )
            > 1e-9
        )
    }

    trigger_actions = {
        str(obj.get("action", "activate_actor"))
        for obj in objects
        if obj.get("type") == "trigger_zone"
    }

    return {
        "objects": objects,
        "object_types": object_types,
        "scene_types": object_types & _SCENE_ACTOR_TYPES,
        "movement_types": movement_types,
        "has_movement": bool(movement_types),
        "has_character_movement": bool(movement_types & {"person", "animal"}),
        "has_secondary_movement": "secondary_qcar2" in movement_types,
        "has_roads": bool(object_types & _ROAD_TYPES),
        "has_guides": any(
            obj.get("type") in _ROAD_TYPES
            and bool((obj.get("guide_line") or {}).get("enabled", False))
            for obj in objects
        ),
        "has_qcar_start": "qcar2_start" in object_types,
        "has_triggers": "trigger_zone" in object_types,
        "trigger_actions": trigger_actions,
        "environment_enabled": bool(
            (track_data.get("environment", {}) or {}).get("enabled", True)
        ),
        "platform_enabled": bool(
            (track_data.get("workspace_platform", {}) or {}).get("enabled", False)
        ),
    }


def _compare_string_value(test: ast.AST, variable_name: str) -> str | None:
    if (
        not isinstance(test, ast.Compare)
        or len(test.ops) != 1
        or len(test.comparators) != 1
        or not isinstance(test.ops[0], ast.Eq)
    ):
        return None

    left = test.left
    right = test.comparators[0]

    if (
        isinstance(left, ast.Name)
        and left.id == variable_name
        and isinstance(right, ast.Constant)
        and isinstance(right.value, str)
    ):
        return right.value

    if (
        isinstance(right, ast.Name)
        and right.id == variable_name
        and isinstance(left, ast.Constant)
        and isinstance(left.value, str)
    ):
        return left.value

    return None


def _prune_string_if_chain(
    node: ast.If, variable_name: str, allowed_values: set[str]
) -> ast.If | None:
    """Prune an if/elif chain comparing one variable to string constants."""
    value = _compare_string_value(node.test, variable_name)

    next_if = (
        node.orelse[0]
        if len(node.orelse) == 1 and isinstance(node.orelse[0], ast.If)
        else None
    )
    pruned_next = (
        _prune_string_if_chain(next_if, variable_name, allowed_values)
        if next_if is not None
        else None
    )

    if value is not None and value not in allowed_values:
        return pruned_next

    node.orelse = [pruned_next] if pruned_next is not None else []
    return node


def _calls_name(node: ast.AST, function_name: str) -> bool:
    for child in ast.walk(node):
        if not isinstance(child, ast.Call):
            continue
        func = child.func
        if isinstance(func, ast.Name) and func.id == function_name:
            return True
    return False


def _loads_name(node: ast.AST, name: str) -> bool:
    return any(
        isinstance(child, ast.Name)
        and isinstance(child.ctx, ast.Load)
        and child.id == name
        for child in ast.walk(node)
    )


def _assignment_target_names(node: ast.AST) -> set[str]:
    targets: list[ast.AST] = []
    if isinstance(node, ast.Assign):
        targets.extend(node.targets)
    elif isinstance(node, ast.AnnAssign):
        targets.append(node.target)
    else:
        return set()

    names: set[str] = set()
    for target in targets:
        for child in ast.walk(target):
            if isinstance(child, ast.Name):
                names.add(child.id)
    return names


def _loaded_names(node: ast.AST) -> set[str]:
    return {
        child.id
        for child in ast.walk(node)
        if isinstance(child, ast.Name) and isinstance(child.ctx, ast.Load)
    }


class _RemoveCallExpressions(ast.NodeTransformer):
    """Remove standalone calls while preserving their enclosing loops/ifs."""

    def __init__(self, function_names: set[str]):
        super().__init__()
        self.function_names = function_names

    def visit_Expr(self, node: ast.Expr):
        if isinstance(node.value, ast.Call):
            func = node.value.func
            if isinstance(func, ast.Name) and func.id in self.function_names:
                return None
        return self.generic_visit(node)


class _FeatureSpecializer(ast.NodeTransformer):
    """Remove runtime paths that cannot be reached by this exported map."""

    def __init__(self, features: dict):
        super().__init__()
        self.features = features

    def visit_FunctionDef(self, node: ast.FunctionDef):
        node = self.generic_visit(node)
        f = self.features

        if node.name == "spawn_scene_actor":
            allowed = f["scene_types"]
            body = []
            for statement in node.body:
                if isinstance(statement, ast.If):
                    value = _compare_string_value(statement.test, "obj_type")
                    if value is not None and value not in allowed:
                        continue
                body.append(statement)
            node.body = body

        elif node.name == "_movement_speed_for_actor":
            allowed = f["movement_types"]
            body = []
            for statement in node.body:
                if isinstance(statement, ast.If):
                    value = _compare_string_value(statement.test, "obj_type")
                    if value is not None and value not in allowed:
                        continue
                body.append(statement)
            node.body = body

        elif node.name == "spawn_scene_actors":
            # Keep the generated type filter as compact as the actual map.
            for statement in node.body:
                if isinstance(statement, ast.Assign):
                    target_names = _assignment_target_names(statement)
                    if "scene_types" in target_names:
                        statement.value = ast.Set(
                            elts=[
                                ast.Constant(value=value)
                                for value in sorted(f["scene_types"])
                            ]
                        )
            if not f["has_movement"]:
                node = _RemoveCallExpressions({"initialize_actor_movement"}).visit(node)
                ast.fix_missing_locations(node)

        elif node.name == "activate_experiment_actor" and not f["has_movement"]:
            node = _RemoveCallExpressions({"initialize_actor_movement"}).visit(node)
            ast.fix_missing_locations(node)

        elif node.name == "initialize_actor_movement" and not f["has_character_movement"]:
            body = []
            for statement in node.body:
                if isinstance(statement, ast.If) and _calls_name(
                    statement, "_create_character_motion_proxy"
                ):
                    continue
                body.append(statement)
            node.body = body

        elif node.name == "fire_trigger":
            allowed_actions = f["trigger_actions"]
            body = []
            for statement in node.body:
                if isinstance(statement, ast.If):
                    statement = _prune_string_if_chain(
                        statement, "action", allowed_actions
                    )
                    if statement is None:
                        continue
                body.append(statement)
            node.body = body

        elif node.name == "run_experiment_runtime" and not f["has_movement"]:
            node = _RemoveCallExpressions({"update_actor_movements"}).visit(node)
            ast.fix_missing_locations(node)
            for child in ast.walk(node):
                if isinstance(child, ast.While):
                    child.test = ast.Name(id="triggers", ctx=ast.Load())
                elif isinstance(child, ast.If) and _loads_name(
                    child.test, "MOVEMENT_STATES"
                ):
                    child.test = ast.UnaryOp(
                        op=ast.Not(),
                        operand=ast.Name(id="triggers", ctx=ast.Load()),
                    )

        elif node.name in {
            "spawn_road_surface",
            "spawn_road_markings",
            "_connection_points_design",
            "spawn_guide",
        }:
            # Remove exact object-type branches that cannot occur in this map.
            # This is especially important for continuous-road helpers: maps
            # containing only legacy road pieces should not carry polyline
            # drawing/export code, keeping generated files compact.
            allowed_road_types = f["object_types"] & _ROAD_TYPES
            body = []
            for statement in node.body:
                if isinstance(statement, ast.If):
                    statement = _prune_string_if_chain(
                        statement,
                        "obj_type",
                        allowed_road_types,
                    )
                    if statement is None:
                        continue
                body.append(statement)
            node.body = body

        elif node.name == "main":
            new_body = []
            skip_next_qcar_if = False

            for statement in node.body:
                if (
                    _calls_name(statement, "apply_environment_settings")
                    and not f["environment_enabled"]
                ):
                    continue
                if (
                    _calls_name(statement, "spawn_workspace_platform")
                    and not f["platform_enabled"]
                ):
                    continue
                if _calls_name(statement, "spawn_road_surface") and not f["has_roads"]:
                    continue
                if (
                    _calls_name(statement, "spawn_connection_patches")
                    and not f["has_roads"]
                ):
                    continue
                if _calls_name(statement, "spawn_road_markings") and not f["has_roads"]:
                    continue
                if _calls_name(statement, "spawn_guide") and not f["has_guides"]:
                    continue
                if (
                    _calls_name(statement, "spawn_scene_actors")
                    and not f["scene_types"]
                ):
                    continue
                if _calls_name(statement, "spawn_qcar2") and not f["has_qcar_start"]:
                    skip_next_qcar_if = True
                    continue
                if _calls_name(statement, "run_experiment_runtime") and not (
                    f["has_triggers"] or f["has_movement"]
                ):
                    continue
                if _loads_name(statement, "QLabsRealTime") and not f["has_qcar_start"]:
                    continue
                if isinstance(statement, ast.If) and skip_next_qcar_if:
                    skip_next_qcar_if = False
                    continue
                if (
                    isinstance(statement, ast.Expr)
                    and isinstance(statement.value, ast.Call)
                    and isinstance(statement.value.func, ast.Attribute)
                    and statement.value.func.attr == "sleep"
                    and not f["has_qcar_start"]
                ):
                    continue
                new_body.append(statement)

            node.body = new_body

        return node


def _reachable_functions(module: ast.Module) -> set[str]:
    functions = {
        node.name: node for node in module.body if isinstance(node, ast.FunctionDef)
    }

    reachable = {"main"} if "main" in functions else set()
    queue = list(reachable)

    while queue:
        name = queue.pop()
        node = functions[name]
        dependencies = _loaded_names(node) & functions.keys()
        for dependency in dependencies:
            if dependency not in reachable:
                reachable.add(dependency)
                queue.append(dependency)

    return reachable


def _prune_module(module: ast.Module) -> ast.Module:
    reachable = _reachable_functions(module)

    import_nodes: list[ast.AST] = []
    assignment_nodes: list[ast.AST] = []
    other_nodes: list[ast.AST] = []

    for node in module.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            import_nodes.append(node)
        elif isinstance(node, ast.FunctionDef):
            if node.name in reachable:
                other_nodes.append(node)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            assignment_nodes.append(node)
        else:
            other_nodes.append(node)

    needed_globals = {"TRACK_DATA"}
    for node in other_nodes:
        needed_globals |= _loaded_names(node)

    # Resolve the dependency closure first, then keep assignments in their
    # original source order.  Preserving order matters for globals such as
    # TRACK_BASE_Z -> ROAD_Z that are evaluated when the generated module is
    # imported.
    changed = True
    while changed:
        changed = False
        for node in assignment_nodes:
            targets = _assignment_target_names(node)
            if targets & needed_globals:
                before = len(needed_globals)
                needed_globals |= _loaded_names(node)
                if len(needed_globals) != before:
                    changed = True

    kept_assignments = [
        node
        for node in assignment_nodes
        if _assignment_target_names(node) & needed_globals
    ]

    retained_nodes = kept_assignments + other_nodes
    used_names: set[str] = set()
    for node in retained_nodes:
        used_names |= _loaded_names(node)

    kept_imports: list[ast.AST] = []
    for node in import_nodes:
        if isinstance(node, ast.Import):
            aliases = []
            for alias in node.names:
                bound = alias.asname or alias.name.split(".", 1)[0]
                if bound in used_names:
                    aliases.append(alias)
            if aliases:
                node.names = aliases
                kept_imports.append(node)
        else:
            aliases = []
            for alias in node.names:
                bound = alias.asname or alias.name
                if bound in used_names:
                    aliases.append(alias)
            if aliases:
                node.names = aliases
                kept_imports.append(node)

    module.body = kept_imports + kept_assignments + other_nodes
    ast.fix_missing_locations(module)
    return module


